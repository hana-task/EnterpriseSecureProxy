using SecureProxy.Api.Security.Headers;

namespace SecureProxy.Api.Forwarding;

/// <summary>
/// Streams the destination's response to the caller: same status code, filtered headers, and the
/// body copied in small chunks (never loaded into memory as a whole) with a size limit.
///
/// Returns Responded when the whole body was written. Otherwise it returns why it stopped. If
/// nothing was sent to the caller yet (HasStarted is false) the controller can still answer with a
/// clean error; if the body was already partly sent, the connection is aborted, so the caller sees
/// a broken response instead of a truncated one that looks complete.
/// </summary>
public static class UpstreamResponseWriter
{
    /// <summary>Marks the answer as coming from the destination and not generated by the proxy.</summary>
    public const string SourceHeaderName = "X-Proxy-Source";
    public const string SourceHeaderValue = "upstream";

    private const int ChunkSizeBytes = 8192;

    public static async Task<ForwardOutcome> WriteAsync(HttpResponse target, ForwardResult result, long maxResponseBytes)
    {
        var upstream = result.Response!;
        var bodyToken = result.BodyCancellationToken;
        var callerToken = target.HttpContext.RequestAborted;

        // When the destination announces its size, refuse before sending anything.
        if (upstream.Content.Headers.ContentLength > maxResponseBytes)
            return ForwardOutcome.ResponseTooLarge;

        try
        {
            await using var body = await upstream.Content.ReadAsStreamAsync(bodyToken);
            var chunk = new byte[ChunkSizeBytes];
            long totalBytes = 0;
            var headersWritten = false;

            int bytesRead;
            while ((bytesRead = await body.ReadAsync(chunk, bodyToken)) > 0)
            {
                // The destination may not announce its size (or lie), so the bytes are counted as they arrive.
                totalBytes += bytesRead;
                if (totalBytes > maxResponseBytes)
                {
                    AbortIfStarted(target);
                    return ForwardOutcome.ResponseTooLarge;
                }

                // Status and headers are set only once the first bytes are really there,
                // so an early failure leaves the response untouched for the error answer.
                if (!headersWritten)
                {
                    WriteStatusAndHeaders(target, upstream);
                    headersWritten = true;
                }
                await target.Body.WriteAsync(chunk.AsMemory(0, bytesRead), bodyToken);
            }

            if (!headersWritten)
                WriteStatusAndHeaders(target, upstream); // an empty body, for example 204 No Content

            return ForwardOutcome.Responded;
        }
        catch (OperationCanceledException)
        {
            AbortIfStarted(target);
            return callerToken.IsCancellationRequested ? ForwardOutcome.CallerCancelled : ForwardOutcome.Timeout;
        }
        catch (Exception exception) when (exception is HttpRequestException or IOException)
        {
            AbortIfStarted(target);

            // Writing to a caller who has gone also fails with an IOException.
            return callerToken.IsCancellationRequested ? ForwardOutcome.CallerCancelled : ForwardOutcome.ConnectionFailed;
        }
    }

    private static void WriteStatusAndHeaders(HttpResponse target, HttpResponseMessage upstream)
    {
        target.StatusCode = (int)upstream.StatusCode;
        foreach (var header in ResponseHeaderFilter.Filter(upstream))
            target.Headers[header.Key] = header.Value;
        target.Headers[SourceHeaderName] = SourceHeaderValue;
    }

    private static void AbortIfStarted(HttpResponse target)
    {
        if (target.HasStarted)
            target.HttpContext.Abort();
    }
}
